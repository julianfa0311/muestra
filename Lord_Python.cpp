void mostrarMapa(char mapa[VIEW_FILAS][VIEW_COLUMNAS], string mensaje) {
    system("cls"); // Limpia la pantalla para dar efecto de movimiento fluido
    cout << mensaje << endl;
    for (int i = 0; i < VIEW_FILAS; i++) {
        for (int j = 0; j < VIEW_COLUMNAS; j++) {
            cout << "" << mapa[i][j] << "";
        }
        cout << endl;
    }
}
// Configurar el tama�o de la consola para la c�mara
void configurarVentana() {
    HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
    COORD coord = {VIEW_COLUMNAS + 5, VIEW_FILAS + 5};
    SetConsoleScreenBufferSize(hConsole, coord);
    SMALL_RECT rect = {0, 0, (SHORT)(VIEW_COLUMNAS + 4), (SHORT)(VIEW_FILAS + 4)};
    SetConsoleWindowInfo(hConsole, TRUE, &rect);
}

// Funci�n de la c�mara que sigue al jugador
void mostrarCamara(char mapa[MAPA_FILAS][MAPA_COLUMNAS], int posX, int posY, string mensaje, int nivel) {
    HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
    COORD coordPos = {0, 0};
    SetConsoleCursorPosition(hConsole, coordPos);

    int inicioX = posX - VIEW_FILAS / 2;
    int inicioY = posY - VIEW_COLUMNAS / 2;

    if (inicioX < 0) inicioX = 0;
    if (inicioX > MAPA_FILAS - VIEW_FILAS) inicioX = MAPA_FILAS - VIEW_FILAS;
    if (inicioY < 0) inicioY = 0;
    if (inicioY > MAPA_COLUMNAS - VIEW_COLUMNAS) inicioY = MAPA_COLUMNAS - VIEW_COLUMNAS;

    cout << "NIVEL: " << nivel << " | " << mensaje << "\n";

    for (int i = inicioX; i < inicioX + VIEW_FILAS; i++) {
        for (int j = inicioY; j < inicioY + VIEW_COLUMNAS; j++) {
            cout << mapa[i][j];
        }
        cout << "\n";
    }
}
